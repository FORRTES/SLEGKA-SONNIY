:- initialization(main).

main :-
    write('Введите список (например, [1,2,3]): '),
    read(List), nl,
    (   is_sorted(List)
    ->  write('Список упорядочен по возрастанию.')
    ;   write('Список не упорядочен.')
    ),
    nl, nl,
    main.

% Базовый случай: пустой список и список из одного элемента — упорядочен
is_sorted([]).
is_sorted([_]).

% Рекурсивный случай: проверка головы и следующего элемента
is_sorted([A, B | Tail]) :-
    A =< B,
    is_sorted([B | Tail]).
